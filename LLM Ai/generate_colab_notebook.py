    "def test_predict(raw_text):\n",
    "    \"\"\"\n",
    "    Hàm test tin nhắn: Xóa sạch toàn bộ ký hiệu đặc biệt gây nhiễu\n",
    "    trước khi đưa vào mô hình PhoBERT xử lý.\n",
    "    \"\"\"\n",
    "    cleaned = clean_text(raw_text)\n",
    "    inputs = tokenizer(cleaned, return_tensors='pt', truncation=True, max_length=256)\n",
    "    device = next(model.parameters()).device\n",
    "    inputs = {k: v.to(device) for k, v in inputs.items()}\n",
    "    \n",
    "    with torch.no_grad():\n",
    "        outputs = model(**inputs)\n",
    "        probs = torch.softmax(outputs.logits, dim=-1).squeeze().cpu().numpy()\n",
    "        pred_lbl = int(np.argmax(probs))\n",
